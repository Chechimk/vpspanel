# shellcheck shell=bash
# vpspanel module: Squid HTTP proxy for tunnelling clients.
# The proxy only forwards to this server itself (SSH, Dropbear, ...), so it is
# never an open proxy. The original squid.conf is saved and restored on removal.

SQUID_CONF=/etc/squid/squid.conf
SQUID_ORIG=/etc/squid/squid.conf.vpspanel-orig
SQUID_PORTS="$VPSP_ETC/squid.ports"

squid_installed() { [[ -f $SQUID_PORTS && -f $SQUID_ORIG ]]; }

squid_write_conf() {
    local ip p
    ip=$(sys_ip)
    {
        echo "# Generated by vpspanel. Original configuration: $SQUID_ORIG"
        while read -r p; do [[ -n $p ]] && echo "http_port $p"; done < "$SQUID_PORTS"
        echo "acl vpsp_self dst 127.0.0.1/32 ${ip}/32"
        echo "http_access allow vpsp_self"
        echo "http_access deny all"
        echo "cache deny all"
        echo "access_log daemon:/var/log/squid/access.log squid"
        echo "via off"
        echo "forwarded_for delete"
        echo "visible_hostname vpspanel"
        echo "shutdown_lifetime 3 seconds"
    } > "$SQUID_CONF"
}

squid_apply() {
    if ! squid -k parse -f "$SQUID_CONF" > /dev/null 2>&1; then
        err "Squid rejected the configuration."; return 1
    fi
    systemctl restart squid
}

squid_install() {
    local -a ports=("$@") p
    for p in "${ports[@]}"; do
        valid_port "$p" || { err "Invalid port: $p"; return 1; }
        port_in_use "$p" && { err "Port $p is already in use."; return 1; }
    done
    apt_install squid || return 1
    [[ -f $SQUID_ORIG ]] || cp -p "$SQUID_CONF" "$SQUID_ORIG"
    mkdir -p "$VPSP_ETC"
    printf '%s\n' "${ports[@]}" > "$SQUID_PORTS"
    squid_write_conf
    squid_apply || return 1
    systemctl enable squid > /dev/null 2>&1
    for p in "${ports[@]}"; do fw_allow "$p"; done
    log_event "squid installed ports ${ports[*]}"
    ok "Squid listening on port(s) ${ports[*]}, forwarding only to this server."
}

squid_add_port() {
    valid_port "$1" || { err "Invalid port."; return 1; }
    grep -qx "$1" "$SQUID_PORTS" && { err "Squid already uses port $1."; return 1; }
    port_in_use "$1" && { err "Port $1 is already in use."; return 1; }
    echo "$1" >> "$SQUID_PORTS"
    squid_write_conf
    squid_apply || { sed -i "/^$1\$/d" "$SQUID_PORTS"; squid_write_conf; squid_apply; return 1; }
    fw_allow "$1"
    ok "Squid port $1 added."
}

squid_remove_port() {
    grep -qx "$1" "$SQUID_PORTS" || { err "Squid does not use port $1."; return 1; }
    (( $(grep -c . "$SQUID_PORTS") > 1 )) || { err "This is the last port. Uninstall Squid instead."; return 1; }
    sed -i "/^$1\$/d" "$SQUID_PORTS"
    squid_write_conf && squid_apply && ok "Squid port $1 removed."
}

squid_uninstall() {
    systemctl stop squid > /dev/null 2>&1
    [[ -f $SQUID_ORIG ]] && mv -f "$SQUID_ORIG" "$SQUID_CONF"
    rm -f "$SQUID_PORTS"
    DEBIAN_FRONTEND=noninteractive apt-get remove -y -q squid > /dev/null 2>&1 || true
    log_event "squid removed"
    ok "Squid removed and its original configuration restored."
}

# ------------------------------------------------------------------ menu ---
squid_info() {
    ui_kv "Status:" "$(fmt_state "$(svc_state squid)")"
    [[ -s $SQUID_PORTS ]] && ui_kv "Ports:" "$(paste -sd, "$SQUID_PORTS")"
}

m_squid_install() {
    local input
    ask input "Squid ports, separated by spaces" "8080 3128" || return
    # shellcheck disable=SC2086
    squid_install $input
}
m_squid_add()    { local p; ask p "New Squid port" && squid_add_port "$p"; }
m_squid_remove() { local p; ask p "Squid port to remove" && squid_remove_port "$p"; }
m_squid_uninstall() { confirm "Uninstall Squid?" && squid_uninstall; }

squid_menu() {
    local -a items
    while true; do
        if squid_installed; then
            items=("Add a port|m_squid_add"
                   "Remove a port|m_squid_remove"
                   "Service status|show_service_status squid"
                   "Restart service|restart_service squid"
                   "Start / stop service|toggle_service squid"
                   "Connection log|show_log /var/log/squid/access.log"
                   "Cache and error log|show_log /var/log/squid/cache.log"
                   "Connection log (live)|follow_log tail -n 30 -f /var/log/squid/access.log"
                   "Uninstall Squid|m_squid_uninstall")
        else
            items=("Install Squid|m_squid_install")
        fi
        menu_show "SQUID PROXY MANAGER" squid_info "${items[@]}" || return 0
    done
}
