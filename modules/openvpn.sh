# shellcheck shell=bash
# vpspanel module: OpenVPN (distribution packages openvpn + easy-rsa, GPL-2.0).
# As in ADMRufu, clients log in with a panel SSH account (PAM, which also
# rejects expired and locked accounts) and share one client file. Unlike
# ADMRufu, the client file holds no private key: client certificates are not
# used (verify-client-cert none), only the CA and a tls-crypt key.

OVPN_DIR="$VPSP_ETC/openvpn"
OVPN_SETTINGS="$OVPN_DIR/settings"    # PROTO PORT CIPHER DNS1 DNS2 HOST
OVPN_CONF=/etc/openvpn/server/vpspanel.conf
OVPN_SVC=openvpn-server@vpspanel
OVPN_DROPIN=/etc/systemd/system/openvpn-server@vpspanel.service.d/vpspanel.conf
OVPN_PAM=/etc/pam.d/openvpn-vpspanel
OVPN_NET=10.9.0.0
OVPN_CLIENT=/root/vpspanel-openvpn.ovpn

ovpn_installed() { [[ -f $OVPN_CONF && -f $OVPN_SETTINGS ]]; }
ovpn_get() { awk -F= -v k="$1" '$1 == k { sub(/^[^=]*=/, ""); print }' "$OVPN_SETTINGS" 2>/dev/null; }
ovpn_set() {
    local tmp; tmp=$(mktemp)
    grep -v "^$1=" "$OVPN_SETTINGS" 2>/dev/null > "$tmp"
    printf '%s=%s\n' "$1" "$2" >> "$tmp"
    install -m 600 "$tmp" "$OVPN_SETTINGS"; rm -f "$tmp"
}

ovpn_plugin() { find /usr/lib -name openvpn-plugin-auth-pam.so 2>/dev/null | head -n1; }
# OpenVPN 2.5+ calls the cipher list data-ciphers; 2.4 (Ubuntu 20.04) ncp-ciphers.
ovpn_ncp() { if openvpn --version 2>/dev/null | head -n1 | grep -qE "OpenVPN 2.4."; then echo ncp-ciphers; else echo data-ciphers; fi; }

ovpn_pki() {
    local er="$OVPN_DIR/easy-rsa"
    rm -rf "$er"; mkdir -p "$er"
    cp -r /usr/share/easy-rsa/* "$er/" || return 1
    (
        cd "$er" || exit 1
        export EASYRSA_BATCH=1 EASYRSA_ALGO=ec EASYRSA_CURVE=prime256v1 EASYRSA_CA_EXPIRE=3650 EASYRSA_CERT_EXPIRE=3650
        ./easyrsa init-pki && EASYRSA_REQ_CN=vpspanel-ca ./easyrsa build-ca nopass && ./easyrsa build-server-full server nopass
    ) > /dev/null 2>&1 || return 1
    install -m 644 "$er/pki/ca.crt" /etc/openvpn/server/vpspanel-ca.crt
    install -m 644 "$er/pki/issued/server.crt" /etc/openvpn/server/vpspanel-server.crt
    install -m 600 "$er/pki/private/server.key" /etc/openvpn/server/vpspanel-server.key
    # OpenVPN 2.5+ syntax first; 2.4 (Ubuntu 20.04) only knows --genkey --secret.
    openvpn --genkey secret /etc/openvpn/server/vpspanel-tc.key > /dev/null 2>&1 \
        || openvpn --genkey --secret /etc/openvpn/server/vpspanel-tc.key > /dev/null 2>&1 || return 1
    chmod 600 /etc/openvpn/server/vpspanel-tc.key
}

ovpn_write_conf() {
    local proto port cipher plugin
    proto=$(ovpn_get PROTO); port=$(ovpn_get PORT); cipher=$(ovpn_get CIPHER); plugin=$(ovpn_plugin)
    cat > "$OVPN_CONF" <<CONF
# Generated by vpspanel from $OVPN_SETTINGS
port $port
proto ${proto}
dev tun
ca vpspanel-ca.crt
cert vpspanel-server.crt
key vpspanel-server.key
dh none
tls-crypt vpspanel-tc.key
topology subnet
server $OVPN_NET 255.255.255.0
push "redirect-gateway def1 bypass-dhcp"
push "dhcp-option DNS $(ovpn_get DNS1)"
push "dhcp-option DNS $(ovpn_get DNS2)"
keepalive 10 120
$(ovpn_ncp) $cipher:AES-256-GCM:AES-128-GCM
cipher $cipher
auth SHA512
user nobody
group nogroup
persist-key
persist-tun
verify-client-cert none
username-as-common-name
duplicate-cn
plugin $plugin openvpn-vpspanel
verb 3
CONF
    [[ $proto == udp ]] && echo "explicit-exit-notify 1" >> "$OVPN_CONF"
}

ovpn_write_client() {
    {
        echo "client"
        echo "dev tun"
        echo "proto $(ovpn_get PROTO)"
        echo "remote $(ovpn_get HOST) $(ovpn_get PORT)"
        echo "resolv-retry infinite"
        echo "nobind"
        echo "persist-key"
        echo "persist-tun"
        echo "remote-cert-tls server"
        echo "auth SHA512"
        echo "cipher $(ovpn_get CIPHER)"
        echo "auth-user-pass"
        echo "auth-nocache"
        echo "verb 3"
        echo "<ca>"; cat /etc/openvpn/server/vpspanel-ca.crt; echo "</ca>"
        echo "<tls-crypt>"; cat /etc/openvpn/server/vpspanel-tc.key; echo "</tls-crypt>"
    } > "$OVPN_CLIENT"
    chmod 600 "$OVPN_CLIENT"
}

ovpn_write_dropin() {
    local iface; iface=$(sys_iface)
    mkdir -p "$(dirname "$OVPN_DROPIN")"
    cat > "$OVPN_DROPIN" <<UNIT
[Unit]
StartLimitIntervalSec=0

[Service]
ExecStartPre=+/usr/sbin/sysctl -qw net.ipv4.ip_forward=1
ExecStartPost=-+/usr/sbin/iptables -t nat -A POSTROUTING -s $OVPN_NET/24 -o ${iface:-eth0} -m comment --comment vpspanel-openvpn -j MASQUERADE
ExecStartPost=-+/usr/sbin/iptables -I FORWARD -s $OVPN_NET/24 -m comment --comment vpspanel-openvpn -j ACCEPT
ExecStartPost=-+/usr/sbin/iptables -I FORWARD -d $OVPN_NET/24 -m state --state RELATED,ESTABLISHED -m comment --comment vpspanel-openvpn -j ACCEPT
ExecStopPost=-+/usr/sbin/iptables -t nat -D POSTROUTING -s $OVPN_NET/24 -o ${iface:-eth0} -m comment --comment vpspanel-openvpn -j MASQUERADE
ExecStopPost=-+/usr/sbin/iptables -D FORWARD -s $OVPN_NET/24 -m comment --comment vpspanel-openvpn -j ACCEPT
ExecStopPost=-+/usr/sbin/iptables -D FORWARD -d $OVPN_NET/24 -m state --state RELATED,ESTABLISHED -m comment --comment vpspanel-openvpn -j ACCEPT
Restart=on-failure
RestartSec=3
UNIT
    systemctl daemon-reload
}

# ovpn_install PROTO PORT CIPHER DNS1 DNS2 HOST
ovpn_install() {
    local proto=$1 port=$2 cipher=$3 dns1=$4 dns2=$5 host=$6
    has_systemd || { err "OpenVPN management requires systemd."; return 1; }
    [[ -c /dev/net/tun ]] || warn "/dev/net/tun is missing: OpenVPN cannot create its tunnel on this server."
    run_step "apt install openvpn easy-rsa" apt_install openvpn easy-rsa iptables || return 1
    [[ -n $(ovpn_plugin) ]] || { err "The OpenVPN PAM plugin was not found."; return 1; }
    mkdir -p "$OVPN_DIR" /etc/openvpn/server && chmod 700 "$OVPN_DIR"
    : > "$OVPN_SETTINGS"
    ovpn_set PROTO "$proto"; ovpn_set PORT "$port"; ovpn_set CIPHER "$cipher"
    ovpn_set DNS1 "$dns1"; ovpn_set DNS2 "$dns2"; ovpn_set HOST "$host"
    # Panel accounts only: the group check keeps other system users out.
    cat > "$OVPN_PAM" <<PAM
auth    required pam_succeed_if.so quiet user ingroup $VPSP_GROUP
auth    required pam_unix.so
account required pam_unix.so
PAM
    run_step "building certificates (easy-rsa)" ovpn_pki || return 1
    ovpn_write_conf
    ovpn_write_dropin
    ovpn_write_client
    run_step "systemctl enable --now openvpn" systemctl enable --now "$OVPN_SVC" \
        || { err "See: journalctl -u $OVPN_SVC"; return 1; }
    fw_allow "$port" "$proto"
    log_event "openvpn installed $proto/$port"
    ok "Client file: $OVPN_CLIENT (clients log in with a panel SSH account)."
}

ovpn_uninstall() {
    systemctl disable --now "$OVPN_SVC" > /dev/null 2>&1 || true
    rm -f "$OVPN_CONF" /etc/openvpn/server/vpspanel-* "$OVPN_PAM" "$OVPN_CLIENT"
    rm -rf "$(dirname "$OVPN_DROPIN")" "$OVPN_DIR"
    systemctl daemon-reload
    log_event "openvpn removed"
    ok "OpenVPN configuration removed (the openvpn package is kept)."
}

ovpn_reconfigure() { ovpn_write_conf; ovpn_write_client; restart_service "$OVPN_SVC"; }

# ------------------------------------------------------------------ menu ---
ovpn_info() {
    if ovpn_installed; then
        printf ' %sPORT:%s %s %s   %sCIPHER:%s %s   %sDNS:%s %s\n' "$C_GRN" "$C_RST" "$(ovpn_get PORT)" "$(ovpn_get PROTO | tr a-z A-Z)" \
            "$C_GRN" "$C_RST" "$(ovpn_get CIPHER)" "$C_GRN" "$C_RST" "$(ovpn_get DNS1)"
        printf ' %sCLIENTS ONLINE:%s %s   %sLOGIN:%s panel SSH accounts\n' "$C_GRN" "$C_RST" \
            "$(awk -F, '$1 == "CLIENT_LIST"' /run/openvpn-server/status-vpspanel.log 2>/dev/null | grep -c .)" "$C_GRN" "$C_RST"
    else
        ui_center "LOGIN WITH PANEL SSH ACCOUNTS" "$C_YLW"
    fi
}

OVPN_DNS_NAMES=("CLOUDFLARE" "GOOGLE" "OPENDNS" "QUAD9" "ADGUARD DNS" "DNS.WATCH")
OVPN_DNS_IPS=("1.1.1.1 1.0.0.1" "8.8.8.8 8.8.4.4" "208.67.222.222 208.67.220.220" "9.9.9.9 149.112.112.112" "94.140.14.14 94.140.15.15" "84.200.69.80 84.200.70.40")
OVPN_CIPHERS=(AES-128-CBC AES-192-CBC AES-256-CBC AES-128-GCM AES-192-GCM AES-256-GCM)

m_ovpn_install() {
    local proto=tcp port cipher dns host a i
    clear 2>/dev/null; ui_title "ENTER THE TRAFFIC TYPE"
    ui_item 1 "TCP"; ui_item 2 "UDP"; ui_line
    ask a "Enter an option" 1 || return; [[ $a == 2 ]] && proto=udp
    if [[ $proto == udp ]]; then ask_port port "OPENVPN PORT" 1194 udp || return
    else ask_port port "OPENVPN PORT" 1194 || return; fi
    ui_title "ENTER THE CIPHER"
    for i in "${!OVPN_CIPHERS[@]}"; do ui_item $((i + 1)) "${OVPN_CIPHERS[i]}"; done; ui_line
    ask a "Enter an option" 6 || return
    valid_int "$a" 1 6 || { err "Invalid option."; return 1; }
    cipher=${OVPN_CIPHERS[a - 1]}
    ui_title "ENTER THE DNS"
    for i in "${!OVPN_DNS_NAMES[@]}"; do ui_item $((i + 1)) "${OVPN_DNS_NAMES[i]}"; done; ui_line
    ask a "Enter an option" 1 || return
    valid_int "$a" 1 "${#OVPN_DNS_NAMES[@]}" || { err "Invalid option."; return 1; }
    dns=${OVPN_DNS_IPS[a - 1]}
    ask host "Address clients connect to" "$(sys_ip)" || return
    ovpn_install "$proto" "$port" "$cipher" "${dns% *}" "${dns#* }" "$host"
}
m_ovpn_show()   { [[ -f $OVPN_CLIENT ]] || ovpn_write_client; cat "$OVPN_CLIENT"; ui_sep; info "Saved as $OVPN_CLIENT"; }
m_ovpn_client() { ovpn_write_client && ok "Client file rebuilt: $OVPN_CLIENT"; }
m_ovpn_keys()   { confirm "Create new certificates? Every client needs the new client file." && run_step "building certificates" ovpn_pki && ovpn_reconfigure; }
m_ovpn_edit_c() { "${EDITOR:-nano}" "$OVPN_CLIENT"; }
m_ovpn_edit_s() { "${EDITOR:-nano}" "$OVPN_CONF" && restart_service "$OVPN_SVC"; }
m_ovpn_uninstall() { confirm "Uninstall OpenVPN?" && ovpn_uninstall; }
m_ovpn_reinstall() { confirm "Reinstall OpenVPN with new settings?" && ovpn_uninstall > /dev/null && m_ovpn_install; }

openvpn_menu() {
    local -a items
    while true; do
        if ovpn_installed; then
            items=("VIEW OVPN CLIENT FILE|m_ovpn_show"
                   "REBUILD OVPN CLIENT FILE|m_ovpn_client"
                   -
                   "RENEW CERTIFICATES|m_ovpn_keys"
                   -
                   "VIEW AND EDIT CLIENT CONFIG (nano)|m_ovpn_edit_c"
                   "VIEW AND EDIT SERVER CONFIG (nano)|m_ovpn_edit_s"
                   -
                   "SERVICE STATUS|show_service_status $OVPN_SVC"
                   "RESTART SERVICE|restart_service $OVPN_SVC"
                   "START/STOP SERVICE $(st_state "$(svc_state "$OVPN_SVC")")|toggle_service $OVPN_SVC"
                   -
                   "LOG OPENVPN|journalctl -u $OVPN_SVC -n 40 --no-pager"
                   "LIVE LOG|follow_log journalctl -u $OVPN_SVC -n 30 -f"
                   "@REINSTALL|m_ovpn_reinstall"
                   "@UNINSTALL|m_ovpn_uninstall")
        else
            items=("INSTALL OPENVPN|m_ovpn_install")
        fi
        menu_show "OPENVPN MANAGER" ovpn_info "${items[@]}" || return 0
    done
}
