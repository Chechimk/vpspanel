# shellcheck shell=bash
# vpspanel module: Stunnel (SSL/TLS wrapper in front of SSH or Dropbear).
# Uses the distribution's stunnel4 package (GPL-2.0+) with a panel-owned
# configuration file and systemd unit.

STN_DIR="$VPSP_ETC/stunnel"
STN_CONF="$STN_DIR/stunnel.conf"
STN_PORTS="$STN_DIR/ports"          # lines of "listen:target"
STN_UNIT=/etc/systemd/system/vpspanel-stunnel.service

stn_installed() { [[ -f $STN_UNIT ]]; }
stn_bin() { command -v stunnel4 || command -v stunnel; }

stn_write_conf() {
    local line listen target
    {
        echo "; Generated by vpspanel - edit with the panel; manual edits are kept until the next port change."
        echo "foreground = yes"
        echo "pid ="
        echo "cert = $STN_DIR/tls/cert.pem"
        echo "key = $STN_DIR/tls/key.pem"
        echo "client = no"
        echo "socket = a:SO_REUSEADDR=1"
        echo "socket = l:TCP_NODELAY=1"
        echo "socket = r:TCP_NODELAY=1"
        while IFS=: read -r listen target; do
            [[ -n $listen ]] || continue
            printf '\n[vpspanel-%s]\naccept = %s\nconnect = 127.0.0.1:%s\n' "$listen" "$listen" "$target"
        done < "$STN_PORTS"
    } > "$STN_CONF"
}

stn_install() {
    local port=$1 target=$2 cert=$3 key=$4
    has_systemd || { err "Stunnel management requires systemd."; return 1; }
    apt_install stunnel4 openssl || return 1
    systemctl disable --now stunnel4 > /dev/null 2>&1 || true
    mkdir -p "$STN_DIR" && chmod 700 "$STN_DIR"
    ssl_copy "$cert" "$key" "$STN_DIR/tls" root || return 1
    echo "$port:$target" > "$STN_PORTS"
    stn_write_conf
    cat > "$STN_UNIT" <<UNIT
[Unit]
Description=Stunnel TLS wrapper (vpspanel)
After=network.target

[Service]
ExecStart=$(stn_bin) $STN_CONF
Restart=on-failure
RestartSec=3

[Install]
WantedBy=multi-user.target
UNIT
    systemctl daemon-reload
    if ! systemctl enable --now vpspanel-stunnel > /dev/null 2>&1; then
        err "Stunnel failed to start. See: journalctl -u vpspanel-stunnel"; return 1
    fi
    fw_allow "$port"
    log_event "stunnel installed $port -> $target"
    ok "Stunnel listening on port $port (TLS) -> local port $target."
}

stn_add_port() {
    local port=$1 target=$2
    grep -q "^$port:" "$STN_PORTS" 2>/dev/null && { err "Stunnel already uses port $port."; return 1; }
    echo "$port:$target" >> "$STN_PORTS"
    stn_write_conf
    if ! systemctl restart vpspanel-stunnel; then
        sed -i "/^$port:/d" "$STN_PORTS"; stn_write_conf; systemctl restart vpspanel-stunnel
        err "Stunnel rejected the new port; change reverted."; return 1
    fi
    fw_allow "$port"
    log_event "stunnel port $port -> $target"
    ok "Added TLS port $port -> local port $target."
}

stn_remove_port() {
    local port=$1
    grep -q "^$port:" "$STN_PORTS" 2>/dev/null || { err "Stunnel does not use port $port."; return 1; }
    (( $(grep -c . "$STN_PORTS") > 1 )) || { err "This is the last port. Uninstall Stunnel instead."; return 1; }
    sed -i "/^$port:/d" "$STN_PORTS"
    stn_write_conf
    systemctl restart vpspanel-stunnel
    log_event "stunnel port $port removed"
    ok "Removed TLS port $port."
}

stn_uninstall() {
    systemctl disable --now vpspanel-stunnel > /dev/null 2>&1 || true
    rm -f "$STN_UNIT"
    rm -rf "$STN_DIR"
    systemctl daemon-reload
    log_event "stunnel removed"
    ok "Stunnel removed (the stunnel4 package is left installed)."
}

# ------------------------------------------------------------------ menu ---
stn_info() {
    ui_kv "Status:" "$(fmt_state "$(svc_state vpspanel-stunnel)")"
    if [[ -s $STN_PORTS ]]; then
        ui_kv "Ports:" "$(sed 's/:/ -> /' "$STN_PORTS" | paste -sd, - | sed 's/,/, /g')"
    fi
}

m_stn_install() {
    local port target cert key
    ask_port port "TLS port (443 is common)" 443 || return
    ask_target_port target || return
    ssl_pick cert key || return
    stn_install "$port" "$target" "$cert" "$key"
}

m_stn_add()    { local p t; ask_port p "New TLS port" && ask_target_port t && stn_add_port "$p" "$t"; }
m_stn_remove() { local p; ask p "TLS port to remove" && stn_remove_port "$p"; }
m_stn_cert()   {
    local cert key
    ssl_pick cert key || return
    ssl_copy "$cert" "$key" "$STN_DIR/tls" root && restart_service vpspanel-stunnel
}
m_stn_edit()   { "${EDITOR:-nano}" "$STN_CONF"; restart_service vpspanel-stunnel; }
m_stn_remove_all() { confirm "Uninstall Stunnel?" && stn_uninstall; }

stunnel_menu() {
    local -a items
    while true; do
        if stn_installed; then
            items=("Add a TLS port|m_stn_add"
                   "Remove a TLS port|m_stn_remove"
                   "Change certificate|m_stn_cert"
                   "Edit configuration (nano)|m_stn_edit"
                   "Service status|show_service_status vpspanel-stunnel"
                   "Restart service|restart_service vpspanel-stunnel"
                   "Start / stop service|toggle_service vpspanel-stunnel"
                   "Live log|follow_log journalctl -u vpspanel-stunnel -n 30 -f"
                   "Uninstall Stunnel|m_stn_remove_all")
        else
            items=("Install Stunnel|m_stn_install")
        fi
        menu_show "STUNNEL (SSL/TLS) MANAGER" stn_info "${items[@]}" || return 0
    done
}
